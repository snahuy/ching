import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { expect, it } from 'vitest';
import { RoomStorage } from './storage';
import { RoomManager, ROOM_LIMITS } from './rooms';
import { DEFAULT_PROFILE } from '../src/avatars';

it('restores identities, private locks, deadline, results and scoring across database reopen without resolving twice', () => {
  const dir = mkdtempSync(join(tmpdir(), 'ching-durability-'));
  let now = 1000;
  const dbPath = join(dir, 'rooms.sqlite');
  let db = new RoomStorage(dbPath);
  let manager = new RoomManager({ now: () => now });
  const a = manager.create('a', 'Host', DEFAULT_PROFILE), guest = manager.join('b', a.code, 'Guest', DEFAULT_PROFILE);
  manager.setSettings('a', { roundSeconds: 15, winsRequired: 1 });
  manager.setReady('a', true); manager.setReady('b', true); manager.start('a');
  const first = manager.view('a');
  manager.lock('a', first.roundId, 'reload');
  db.save(manager.snapshot()); db.close();
  db = new RoomStorage(dbPath); manager = new RoomManager({ now: () => now }); manager.restore(db.load()!);
  manager.resume('a2', a.code, a.token); manager.resume('b2', a.code, guest.token);
  expect(manager.view('b2').players).toHaveLength(2);
  expect(manager.view('b2').phaseEndsAt).toBe(first.phaseEndsAt);
  expect(manager.view('b2').selfAction).toBeNull(); expect(manager.view('b2').history).toEqual([]);
  expect(() => manager.lock('a2', first.roundId, 'block1')).toThrow('already locked');
  manager.lock('b2', first.roundId, 'reload'); now += ROOM_LIMITS.clapMs; manager.tick();
  now += ROOM_LIMITS.moveMs; manager.tick(); now += ROOM_LIMITS.revealMs; manager.tick();
  const second = manager.view('a2');
  manager.lock('a2', second.roundId, 'ching', guest.playerId); manager.lock('b2', second.roundId, 'reload');
  now += ROOM_LIMITS.clapMs; manager.tick();
  db.save(manager.snapshot()); db.close();
  db = new RoomStorage(dbPath); manager = new RoomManager({ now: () => now }); manager.restore(db.load()!);
  manager.resume('a3', a.code, a.token); manager.resume('b3', a.code, guest.token);
  now += ROOM_LIMITS.moveMs; manager.tick(); now += ROOM_LIMITS.revealMs; manager.tick();
  expect(manager.view('a3').championId).toBe(a.playerId);
  expect(manager.view('a3').players.find(p => p.id === a.playerId)?.score).toBe(1);
  for (let i = 0; i < 3; i++) manager.tick();
  expect(manager.view('a3').history).toHaveLength(2);
  expect(manager.view('a3').players.find(p => p.id === a.playerId)?.score).toBe(1);
  db.close(); rmSync(dir, { recursive: true });
});
